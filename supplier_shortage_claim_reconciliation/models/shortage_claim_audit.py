from odoo import api, fields, models
from odoo.exceptions import AccessError
from odoo.fields import Domain


class ShortageClaimAudit(models.Model):
    _name = 'supplier.shortage.claim.audit'
    _description = 'Supplier Claim Business Audit'
    _order = 'event_datetime desc, id desc'
    _check_company_auto = True
    _allow_sudo_commands = False

    claim_id = fields.Many2one('supplier.shortage.claim', required=False, readonly=True, check_company=True, ondelete='restrict', index=True)
    receipt_exception_id = fields.Many2one('supplier.shortage.receipt.exception', readonly=True, check_company=True, ondelete='restrict', index=True)
    _audit_parent = models.Constraint('CHECK ((claim_id IS NOT NULL)::integer + (receipt_exception_id IS NOT NULL)::integer = 1)', 'Audit history must have exactly one business parent.')

    company_id = fields.Many2one('res.company', required=True, readonly=True, index=True)
    event_type = fields.Selection([
        ('exception_detected', 'Receiving Exception Detected'), ('exception_changed', 'Receiving Source Changed'),
        ('exception_assigned', 'Exception Assigned'), ('exception_noted', 'Review Note Recorded'),
        ('exception_started', 'Exception Review Started'), ('exception_resolved', 'Exception Resolved'),
        ('exception_dismissed', 'Exception Dismissed'), ('exception_reopened', 'Exception Reopened'),
        ('evidence_revised','Evidence Revision Created'),('evidence_assigned','Evidence Review Assigned'),
        ('warehouse_revised','Warehouse Observation Revised'), ('warehouse_recorded','Warehouse Observation Recorded'),('warehouse_reviewed','Warehouse Observation Reviewed'),
        ('readiness_invalidated','Evidence Readiness Invalidated'),('readiness_evaluated','Evidence Readiness Evaluated'),
        ('evidence_exception','Additional Evidence Exception Reviewed'),
        ('prepared','Draft Prepared from Candidates'), ('allocation_created','Quantity Reserved'),
        ('allocation_changed','Reservation Corrected'), ('allocation_released','Reservation Released'),
        ('allocation_revalidated','Preparation Revalidated'), ('evidence_added','Evidence Added'),
        ('evidence_noted','Evidence Note Changed'), ('evidence_reviewed','Evidence Review Recorded'),
        ('created', 'Claim Created'), ('lines_added', 'Claim Lines Added'),
        ('fields_changed', 'Business Fields Changed'), ('quantity_changed', 'Proposed Quantity Changed'),
        ('submitted', 'Submitted for Review'), ('returned', 'Returned for Correction'),
        ('valuation_refreshed', 'Draft Valuation Refreshed'), ('audit_enabled', 'Audit Logging Enabled'),
    ], required=True, readonly=True)
    actor_id = fields.Many2one('res.users', required=True, readonly=True, ondelete='restrict')
    event_datetime = fields.Datetime(required=True, readonly=True, index=True)
    old_state = fields.Selection([('draft', 'Draft'), ('under_review', 'Under Review')], readonly=True)
    new_state = fields.Selection([('draft', 'Draft'), ('under_review', 'Under Review')], readonly=True)
    change_summary = fields.Text(required=True, readonly=True)
    reason = fields.Text(readonly=True)
    details = fields.Html(readonly=True)
    valuation_basis = fields.Json(readonly=True)

    def _access_domain(self, operation):
        domain = super()._access_domain(operation)
        # Preparation audit snapshots include source billing quantities/pricing.
        # Header access alone must not expose inaccessible candidate-backed lines.
        return domain & (Domain('claim_id','=',False) | ~Domain('claim_id.claim_line_ids','any!',~Domain('id','access','read')))

    @api.model_create_multi
    def create(self, vals_list):
        raise AccessError(self.env._('Audit events can only be generated by successful claim operations.'))

    def write(self, vals):
        raise AccessError(self.env._('Business audit history is immutable.'))

    def unlink(self):
        raise AccessError(self.env._('Business audit history cannot be deleted.'))

    @api.model
    def _append(self, claims, event_type, summaries, *, old_state=None, new_state=None, reason=None, details=None, basis=None):
        if not claims:
            return
        claims.check_access('write')
        now = fields.Datetime.now()
        values = [{'claim_id': claim.id, 'company_id': claim.company_id.id,
                   'event_type': event_type, 'actor_id': self.env.uid, 'event_datetime': now,
                   'old_state': old_state, 'new_state': new_state or claim.state,
                   'change_summary': summaries.get(claim.id, '') if isinstance(summaries, dict) else summaries,
                   'reason': reason, 'details': (details or {}).get(claim.id),
                   'valuation_basis': (basis or {}).get(claim.id)} for claim in claims]
        # Only this private append path elevates insertion, after caller access checks.
        # No elevated reads or recordsets escape; public mutation methods always deny.
        super(ShortageClaimAudit, self.sudo().with_context({})).create(values)

    def export_data(self, fields_to_export):
        self.check_access('read')
        return super().export_data(fields_to_export)

